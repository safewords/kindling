//! `autoexec.ipxe`, generated.
//!
//! Stock iPXE — the `ipxe.efi` or `undionly.kpxe` anybody downloads, with no
//! script built in — asks the TFTP server it was loaded from for
//! `autoexec.ipxe` before it does anything else, and runs it if it is there.
//! Without it, such a loader falls back to the boot filename in the DHCP
//! answer, and when that answer came from a proxy beside the network's own
//! DHCP server some builds never use it and say "Nothing to boot" (seen with a
//! stock `ipxe.efi` loaded by a 10GbE NIC's UEFI PXE).
//!
//! So this server always answers that request itself, with a script that
//! chains to its own `/boot.ipxe`. It is built from the HTTP base the server
//! is running with, which means it cannot be forgotten when a server is set
//! up, cannot point at an address the server no longer has, and never has to
//! be staged into the boot root by hand. A file called `autoexec.ipxe` in the
//! root is not served (`pxe:doctor` says so).
//!
//! Loaders built by `pxe:ipxe --build` carry their own script and never ask
//! for this file, so it changes nothing for them.

/// The name stock iPXE asks for, as it asks for it.
pub const NAME: &str = "autoexec.ipxe";

/// The script, for a server reachable at `http_base`.
///
/// If the chain fails — the HTTP port is blocked, the server is down — the
/// machine is not left at an iPXE prompt nobody is watching: it says why on
/// its console and hands back to the firmware's next boot device.
pub fn script(http_base: &str) -> String {
    let base = http_base.trim_end_matches('/');
    format!(
        "#!ipxe\n\
         # Generated by kindling, not read from a file: stock iPXE asks the TFTP\n\
         # server it was loaded from for autoexec.ipxe first, and this sends it to\n\
         # kindling's own boot script.\n\
         echo kindling: asking {base}/boot.ipxe what to boot\n\
         isset ${{ip}} || dhcp || goto failed\n\
         chain --autofree {base}/boot.ipxe || goto failed\n\
         exit 0\n\
         :failed\n\
         echo kindling: {base}/boot.ipxe could not be reached; continuing the firmware boot order\n\
         sleep 5\n\
         exit 1\n"
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn it_chains_to_this_servers_boot_script_and_falls_back_to_the_firmware() {
        let script = script("http://10.0.0.2:8081/");
        assert!(script.starts_with("#!ipxe\n"), "{script}");
        assert!(
            script.contains("chain --autofree http://10.0.0.2:8081/boot.ipxe || goto failed"),
            "{script}"
        );
        assert!(script.contains("isset ${ip} || dhcp"), "{script}");
        assert!(script.trim_end().ends_with("exit 1"), "{script}");
        assert!(
            !script.contains("shell"),
            "nobody is watching a headless prompt"
        );
    }
}
